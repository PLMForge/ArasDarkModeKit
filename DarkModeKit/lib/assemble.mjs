#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { parseArgs, requireArg, createLogger, readJson, writeJson, writeIfChanged, walkFiles, splitBom, encodeText, readText, shortHash, defaultStagingDir, KIT_DIR, isMain, mkdirp } from './util.mjs';

const log = createLogger('assemble');

export const RUNTIME_ORDER = ['theme-init.js', 'scope-markers.js', 'hook-stylesheets.js', 'hook-components.js', 'hook-svg.js', 'hook-reports.js', 'hook-apps.js', 'adaptForDark.js', 'theme-runtime.js', 'theme-menu.js', 'form-field-colors.js'];
export const DARK_CSS_ORDER = [
	['staging', 'client/gen/tokens.css'],
	['staging', 'client/gen/overrides.css'],
	['staging', 'client/gen/icons-dark.css'],
	['kit', 'hand/runtime-dark.css']
];
export const HAND_COPIES = ['report-dark.css', 'pdftron-dark.css', 'pdftron-dark-config.js'];
export const GROUPS = [
	{ name: 'client', from: 'client', to: 'Innovator/Client/darkmode' },
	{ name: 'images', from: 'images-dark', to: 'Innovator/Client/images-dark' },
	{ name: 'oauth', from: 'oauth', to: 'OAuthServer/wwwroot/css/darkmode' }
];

const text = (file) => splitBom(fs.readFileSync(file)).body.toString('utf8');

export function buildBoot({ staging, kit, version, assets = {} }) {
	const data = {};
	for (const k of ['palette', 'sheets', 'icons', 'scopes']) {
		const f = path.join(staging, 'data', `${k}.json`);
		const empty = k === 'scopes' ? [] : {};
		if (fs.existsSync(f)) data[k] = readJson(f);
		else {
			log.warn(`data/${k}.json missing in staging: __dmData.${k} = ${JSON.stringify(empty)}`);
			data[k] = empty;
		}
	}
	const parts = [
		'/* aras-darkmode dm-boot.js: generated by DarkModeKit/lib/assemble.mjs. Do not edit; re-run apply-darkmode.ps1. */',
		`window.__dmData = ${JSON.stringify({ version: version || null, palette: data.palette, sheets: data.sheets, icons: data.icons, scopes: data.scopes, assets })};`
	];
	const included = [];
	for (const f of RUNTIME_ORDER) {
		const p = path.join(kit, 'runtime', f);
		if (!fs.existsSync(p)) {
			log.warn(`runtime/${f} missing: skipped`);
			continue;
		}
		parts.push(`/* ---- runtime/${f} ---- */`, text(p).replace(/\s+$/, ''), ';');
		included.push(f);
	}
	return { content: parts.join('\n') + '\n', included };
}

export function buildDarkCss({ staging, kit }) {
	const parts = ['/* aras-darkmode dark.css: generated by DarkModeKit/lib/assemble.mjs. Do not edit. */'];
	const included = [];
	for (const [where, rel] of DARK_CSS_ORDER) {
		const p = path.join(where === 'kit' ? kit : staging, ...rel.split('/'));
		if (!fs.existsSync(p)) {
			log.warn(`${where === 'kit' ? '' : 'staging/'}${rel} missing: skipped in dark.css`);
			continue;
		}
		const css = text(p);
		if (/^\s*@(import|charset)\b/m.test(css)) log.warn(`${rel} contains @import/@charset; it is ignored when not first in dark.css`);
		parts.push(`/* ---- ${rel} ---- */`, css.replace(/\s+$/, ''));
		included.push(rel);
	}
	return { content: parts[0] + '\n@media screen {\n' + parts.slice(1).join('\n') + '\n}\n', included };
}

function removeEmptyDirs(dir) {
	if (!fs.existsSync(dir)) return;
	for (const e of fs.readdirSync(dir, { withFileTypes: true })) if (e.isDirectory()) removeEmptyDirs(path.join(dir, e.name));
	if (!fs.readdirSync(dir).length) fs.rmdirSync(dir);
}

export function assemble({ target, staging, kit = KIT_DIR, version, dryRun = false, uninstall = false }) {
	const res = { dryRun, uninstall, written: 0, unchanged: 0, deleted: 0, files: [], deletedFiles: [], skippedGroups: [], boot: null, darkCss: null };
	if (!uninstall) {
		const sc = path.join(staging, 'client');
		mkdirp(sc);
		const css = buildDarkCss({ staging, kit });
		fs.writeFileSync(path.join(sc, 'dark.css'), css.content);
		res.darkCss = css.included;
		for (const f of HAND_COPIES) {
			const p = path.join(kit, 'hand', f);
			if (fs.existsSync(p)) fs.copyFileSync(p, path.join(sc, f));
			else log.warn(`hand/${f} missing: skipped`);
		}
		const assets = {};
		for (const r of walkFiles(sc)) if (r !== 'dm-boot.js') assets[r] = shortHash(fs.readFileSync(path.join(sc, ...r.split('/'))));
		res.assets = assets;
		const boot = buildBoot({ staging, kit, version, assets });
		fs.writeFileSync(path.join(sc, 'dm-boot.js'), boot.content);
		res.boot = boot.included;
	}
	for (const g of GROUPS) {
		const outDir = path.join(target, ...g.to.split('/'));
		const srcDir = path.join(staging, ...g.from.split('/'));
		const produced = uninstall ? [] : walkFiles(srcDir);
		if (g.name === 'oauth' && !fs.existsSync(path.join(target, 'OAuthServer', 'wwwroot'))) {
			if (produced.length) log.warn('OAuthServer/wwwroot not in target: OAuth files not deployed');
			continue;
		}
		if (!uninstall && !produced.length) {
			res.skippedGroups.push(g.name);
			log.warn(`staging/${g.from} is empty: ${g.to} left as it is`);
			continue;
		}
		const keep = new Set(produced.map((r) => r.toLowerCase()));
		for (const r of produced) {
			const changed = writeIfChanged(path.join(outDir, ...r.split('/')), fs.readFileSync(path.join(srcDir, ...r.split('/'))), { dryRun });
			if (changed) {
				res.written++;
				res.files.push(`${g.to}/${r}`);
				if (dryRun) log.info(`would write ${g.to}/${r}`);
			} else res.unchanged++;
		}
		for (const r of walkFiles(outDir)) {
			if (keep.has(r.toLowerCase())) continue;
			if (!dryRun) fs.unlinkSync(path.join(outDir, ...r.split('/')));
			res.deleted++;
			res.deletedFiles.push(`${g.to}/${r}`);
			log.info(`${dryRun ? 'would delete' : 'deleted'} ${g.to}/${r}`);
		}
		if (!dryRun) removeEmptyDirs(outDir);
	}
	log.info(`${uninstall ? 'uninstall' : 'assemble'}${dryRun ? ' (dry run)' : ''}: ${res.written} ${dryRun ? 'pending' : 'written'}, ${res.unchanged} unchanged, ${res.deleted} ${dryRun ? 'to delete' : 'deleted'}`);
	return res;
}

export function nextRevision(cur, now = new Date()) {
	if (/^\d+$/.test(cur)) return String(Number(cur) + 1);
	if (cur === 'std' || cur === '') return '1';
	const p = (n) => String(n).padStart(2, '0');
	return `${now.getFullYear()}${p(now.getMonth() + 1)}${p(now.getDate())}${p(now.getHours())}${p(now.getMinutes())}`;
}

export function bumpRevision({ target, dryRun = false }) {
	const file = path.join(target, 'Innovator', 'Client', 'InnovatorClient.config');
	const { text: t, bom } = readText(file);
	const re = /(<cachingModule\b[^>]*?\bfilesRevision=")([^"]*)(")/;
	const m = re.exec(t);
	if (!m) {
		log.warn('no cachingModule/@filesRevision in InnovatorClient.config: not bumped');
		return { bumped: false };
	}
	const to = nextRevision(m[2]);
	if (!dryRun) fs.writeFileSync(file, encodeText(t.replace(re, `$1${to}$3`), bom));
	log.info(`filesRevision ${m[2]} -> ${to}${dryRun ? ' (dry run, not written)' : ''}`);
	return { bumped: !dryRun, from: m[2], to };
}

if (isMain(import.meta.url)) {
	try {
		const args = parseArgs();
		const target = path.resolve(requireArg(args, 'target'));
		let res;
		if (args.bumpRevision) res = bumpRevision({ target, dryRun: !!args.dryRun });
		else
			res = assemble({
				target,
				staging: args.staging ? path.resolve(args.staging) : defaultStagingDir(target),
				kit: args.kit ? path.resolve(args.kit) : KIT_DIR,
				version: typeof args.version === 'string' ? args.version : null,
				dryRun: !!args.dryRun,
				uninstall: !!args.uninstall
			});
		if (args.result) writeJson(path.resolve(args.result), res);
	} catch (e) {
		log.error(e.stack || e.message);
		process.exit(1);
	}
}
