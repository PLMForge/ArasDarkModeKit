const clamp = (x, lo, hi) => Math.min(hi, Math.max(lo, x));
function num(tok, scale) {
	tok = tok.trim();
	if (/%$/.test(tok)) return (parseFloat(tok) / 100) * scale;
	return parseFloat(tok);
}
function hslToRgb(h, s, l) {
	h = ((h % 360) + 360) % 360;
	s = clamp(s, 0, 1);
	l = clamp(l, 0, 1);
	const k = (n) => (n + h / 30) % 12;
	const a = s * Math.min(l, 1 - l);
	const f = (n) => l - a * Math.max(-1, Math.min(k(n) - 3, 9 - k(n), 1));
	return [f(0) * 255, f(8) * 255, f(4) * 255];
}
function hueDeg(tok) {
	tok = tok.trim().toLowerCase();
	const v = parseFloat(tok);
	if (/rad$/.test(tok)) return (v * 180) / Math.PI;
	if (/grad$/.test(tok)) return v * 0.9;
	if (/turn$/.test(tok)) return v * 360;
	return v;
}
export function parseColor(src) {
	if (src == null) return null;
	let s = String(src).trim().toLowerCase();
	if (s === 'transparent') return { kw: 'transparent', r: 0, g: 0, b: 0, a: 0 };
	if (s === 'currentcolor') return { kw: 'currentcolor' };
	let sys = null;
	if (SYSTEM[s]) {
		sys = s;
		s = SYSTEM[s][0];
	} else if (NAMED[s]) s = NAMED[s];
	let m = s.match(/^#([0-9a-f]{3,8})$/);
	if (m) {
		let h = m[1];
		if (h.length === 3 || h.length === 4) h = [...h].map((c) => c + c).join('');
		if (h.length !== 6 && h.length !== 8) return null;
		const c = {
			r: parseInt(h.slice(0, 2), 16), g: parseInt(h.slice(2, 4), 16), b: parseInt(h.slice(4, 6), 16),
			a: h.length === 8 ? parseInt(h.slice(6, 8), 16) / 255 : 1
		};
		if (sys) c.sys = sys;
		return c;
	}
	m = s.match(/^(rgba?|hsla?)\(([^()]*)\)$/);
	if (!m) return null;
	const body = m[2].trim();
	let parts, alpha;
	if (body.includes(',')) {
		parts = body.split(',').map((x) => x.trim());
		if (parts.length === 4) alpha = parts.pop();
	} else {
		const [main, al] = body.split('/');
		parts = main.trim().split(/\s+/);
		alpha = al;
	}
	if (parts.length !== 3) return null;
	let a = 1;
	if (alpha != null && alpha.trim() !== '') a = /%$/.test(alpha.trim()) ? parseFloat(alpha) / 100 : parseFloat(alpha);
	if ([a].some(Number.isNaN)) return null;
	let r, g, b;
	if (m[1][0] === 'r') {
		[r, g, b] = parts.map((p) => num(p, 255));
	} else {
		[r, g, b] = hslToRgb(hueDeg(parts[0]), num(parts[1], 1) / (/%$/.test(parts[1]) ? 1 : 100), num(parts[2], 1) / (/%$/.test(parts[2]) ? 1 : 100));
	}
	if ([r, g, b].some(Number.isNaN)) return null;
	return { r: clamp(r, 0, 255), g: clamp(g, 0, 255), b: clamp(b, 0, 255), a: clamp(a, 0, 1) };
}
const h2 = (x) => Math.round(clamp(x, 0, 255)).toString(16).padStart(2, '0');
export const toHex6 = (c) => '#' + h2(c.r) + h2(c.g) + h2(c.b);
export const toHex8 = (c) => toHex6(c) + h2((c.a == null ? 1 : c.a) * 255);
export const hexKey = (c) => (c.a == null || c.a >= 1 ? toHex6(c) : toHex8(c));
export function toCss(c) {
	if (!c) return null;
	if (c.kw === 'transparent' || c.a === 0) return 'transparent';
	if (c.a == null || c.a >= 1) return toHex6(c);
	return `rgba(${Math.round(c.r)}, ${Math.round(c.g)}, ${Math.round(c.b)}, ${+c.a.toFixed(3)})`;
}
export function hexToRgb(hex) {
	const c = parseColor(hex);
	return c ? [c.r, c.g, c.b] : null;
}
export const norm = (x) => toHex6(typeof x === 'string' ? parseColor(x) : x);

const toLin = (c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const toGamma = (c) => (c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055);
const unit = (x) => {
	const c = typeof x === 'string' ? parseColor(x) : x;
	return [c.r / 255, c.g / 255, c.b / 255];
};
function luminance(rgb) {
	const [r, g, b] = rgb.map(toLin);
	return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}
export const lum = (x) => luminance(unit(x));
export function contrast(a, b) {
	const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p);
	return (x + 0.05) / (y + 0.05);
}
function srgbToOklch(rgb) {
	const [r, g, b] = rgb.map(toLin);
	const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
	const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
	const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
	const L = 0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s;
	const A = 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s;
	const B = 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s;
	return [L, Math.hypot(A, B), Math.atan2(B, A)];
}
export const oklch = (x) => srgbToOklch(unit(x));
function oklchToLinear(L, C, H) {
	const a = C * Math.cos(H), b = C * Math.sin(H);
	const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3;
	const m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3;
	const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3;
	return [
		4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
		-1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
		-0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s
	];
}
const rgbUnitToHex = (rgb) =>
	'#' + rgb.map((c) => Math.round(Math.min(1, Math.max(0, c)) * 255).toString(16).padStart(2, '0')).join('');
export function oklchToHex(L, C, H) {
	let lin = oklchToLinear(L, C, H);
	while (C > 0 && lin.some((c) => c < -0.001 || c > 1.001)) {
		C -= 0.005;
		lin = oklchToLinear(L, C, H);
	}
	return rgbUnitToHex(lin.map((c) => toGamma(Math.min(1, Math.max(0, c)))));
}

export function adaptForDark(hex, { bg = '#1e2027', minContrast = 3, maxL = 0.86 } = {}) {
	if (!hex) return hex;
	let [L, C, H] = oklch(hex);
	if (L > maxL) L = maxL;
	let out = oklchToHex(L, C, H);
	while (contrast(out, bg) < minContrast && L < 1) {
		L += 0.01;
		out = oklchToHex(L, C, H);
	}
	return out;
}

export function tintAtContrast(target, surface, tint, dir = 'lighter') {
	if (tint.maxContrast && dir !== 'darker') target = Math.min(target, tint.maxContrast);
	const Ys = lum(surface);
	const Yt = dir === 'darker' ? (Ys + 0.05) / target - 0.05 : target * (Ys + 0.05) - 0.05;
	const H = (tint.hue * Math.PI) / 180;
	let lo = 0, hi = 1;
	for (let i = 0; i < 60; i++) {
		const mid = (lo + hi) / 2;
		if (lum(oklchToHex(mid, tint.chroma, H)) < Yt) lo = mid;
		else hi = mid;
	}
	let best = null;
	for (let d = -0.004; d <= 0.0041; d += 0.001) {
		const hx = oklchToHex((lo + hi) / 2 + d, tint.chroma, H);
		const err = Math.abs(Math.log(contrast(hx, surface) / target));
		if (!best || err < best.err - 1e-12) best = { hx, err };
	}
	return best.hx;
}
export function bgTint(light, text, textContrast, chroma) {
	const [, C0, H] = oklch(light);
	const C = chroma == null ? C0 : chroma;
	const Yt = (lum(text) + 0.05) / textContrast - 0.05;
	let lo = 0, hi = 1;
	for (let i = 0; i < 60; i++) {
		const mid = (lo + hi) / 2;
		if (lum(oklchToHex(mid, C, H)) < Yt) lo = mid;
		else hi = mid;
	}
	return oklchToHex(lo, C, H);
}
export function hueMatch(light, surfaceLight, surface, tint) {
	const [, C, H] = oklch(light);
	return tintAtContrast(contrast(light, surfaceLight), surface, { hue: (H * 180) / Math.PI, chroma: Math.min(C, 0.06), maxContrast: tint.maxContrast }, 'lighter');
}

function lab(x) {
	const [r, g, b] = unit(x).map(toLin);
	const X = (0.4124564 * r + 0.3575761 * g + 0.1804375 * b) / 0.95047;
	const Y = 0.2126729 * r + 0.7151522 * g + 0.072175 * b;
	const Z = (0.0193339 * r + 0.119192 * g + 0.9503041 * b) / 1.08883;
	const f = (t) => (t > 216 / 24389 ? Math.cbrt(t) : ((24389 / 27) * t + 16) / 116);
	return [116 * f(Y) - 16, 500 * (f(X) - f(Y)), 200 * (f(Y) - f(Z))];
}
export function dE2000(h1, h2) {
	const [L1, a1, b1] = lab(h1), [L2, a2, b2] = lab(h2);
	const rad = Math.PI / 180;
	const C1 = Math.hypot(a1, b1), C2 = Math.hypot(a2, b2), Cb = (C1 + C2) / 2;
	const G = 0.5 * (1 - Math.sqrt(Cb ** 7 / (Cb ** 7 + 25 ** 7)));
	const ap1 = (1 + G) * a1, ap2 = (1 + G) * a2;
	const Cp1 = Math.hypot(ap1, b1), Cp2 = Math.hypot(ap2, b2);
	const hp = (b, a) => {
		if (!a && !b) return 0;
		const h = Math.atan2(b, a) / rad;
		return h < 0 ? h + 360 : h;
	};
	const hp1 = hp(b1, ap1), hp2 = hp(b2, ap2);
	const dL = L2 - L1, dC = Cp2 - Cp1;
	let dh = 0;
	if (Cp1 * Cp2) {
		dh = hp2 - hp1;
		if (dh > 180) dh -= 360;
		else if (dh < -180) dh += 360;
	}
	const dH = 2 * Math.sqrt(Cp1 * Cp2) * Math.sin((dh / 2) * rad);
	const Lb = (L1 + L2) / 2, Cpb = (Cp1 + Cp2) / 2;
	let hb = hp1 + hp2;
	if (Cp1 * Cp2) {
		if (Math.abs(hp1 - hp2) > 180) hb += hb < 360 ? 360 : -360;
		hb /= 2;
	}
	const T = 1 - 0.17 * Math.cos((hb - 30) * rad) + 0.24 * Math.cos(2 * hb * rad) + 0.32 * Math.cos((3 * hb + 6) * rad) - 0.2 * Math.cos((4 * hb - 63) * rad);
	const dTh = 30 * Math.exp(-(((hb - 275) / 25) ** 2));
	const Rc = 2 * Math.sqrt(Cpb ** 7 / (Cpb ** 7 + 25 ** 7));
	const Sl = 1 + (0.015 * (Lb - 50) ** 2) / Math.sqrt(20 + (Lb - 50) ** 2), Sc = 1 + 0.045 * Cpb, Sh = 1 + 0.015 * Cpb * T;
	const Rt = -Math.sin(2 * dTh * rad) * Rc;
	return Math.sqrt((dL / Sl) ** 2 + (dC / Sc) ** 2 + (dH / Sh) ** 2 + Rt * (dC / Sc) * (dH / Sh));
}

export function mixHex(a, b, p) {
	const x = parseColor(a), y = parseColor(b);
	return toHex6({ r: x.r * p + y.r * (1 - p), g: x.g * p + y.g * (1 - p), b: x.b * p + y.b * (1 - p) });
}
export function colorMix(a, b, p) {
	const aa = a.a == null ? 1 : a.a, ba = b.a == null ? 1 : b.a;
	const A = aa * p + ba * (1 - p);
	if (A <= 0) return { r: 0, g: 0, b: 0, a: 0 };
	const ch = (k) => (a[k] * aa * p + b[k] * ba * (1 - p)) / A;
	return { r: ch('r'), g: ch('g'), b: ch('b'), a: A };
}
export function composite(fg, bg) {
	const a = fg.a == null ? 1 : fg.a;
	return { r: fg.r * a + bg.r * (1 - a), g: fg.g * a + bg.g * (1 - a), b: fg.b * a + bg.b * (1 - a), a: 1 };
}
export const rgbChroma = (c) => Math.max(c.r, c.g, c.b) - Math.min(c.r, c.g, c.b);
export function rgbHue({ r, g, b }) {
	const mx = Math.max(r, g, b), mn = Math.min(r, g, b), d = mx - mn;
	if (!d) return 0;
	let h = mx === r ? ((g - b) / d) % 6 : mx === g ? (b - r) / d + 2 : (r - g) / d + 4;
	h *= 60;
	return h < 0 ? h + 360 : h;
}
